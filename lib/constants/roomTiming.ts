/**
 * 房間節奏相關的時間常數，伺服器（安排下一題的開始時間）與客戶端（判斷目前該顯示什麼畫面）
 * 都要用同一份數字，才不會兩邊各自認定的「答案公布要顯示幾秒」對不起來。
 *
 * 設計原則：answer 揭曉／流局的那一刻，伺服器立刻把房間狀態推進到下一題，並把下一題的
 * roundStartedAt 直接排定成「現在＋REVEAL_DISPLAY_SEC」，不需要任何一個客戶端（尤其房主端）
 * 用自己的計時器算好時間再另外呼叫一次 API 才觸發換題。所有客戶端純粹依這幾個絕對時間戳
 * 自己算「現在該顯示什麼」，避免疊加「輪詢延遲＋本地計時器＋額外一次 API 往返」這幾層延遲。
 */

/** 每題開始前的倒數秒數（從 roundStartedAt 起算，這段時間內顯示倒數數字，還不播放音訊） */
export const COUNTDOWN_SEC = 3;

/** 答對／流局公布答案後，顯示答案的秒數，之後才正式進入下一題的倒數 */
export const REVEAL_DISPLAY_SEC = 3;

/** 答案公布後，判斷「現在是否還在顯示答案」的視窗（毫秒） */
export const REVEAL_DISPLAY_MS = REVEAL_DISPLAY_SEC * 1000;
