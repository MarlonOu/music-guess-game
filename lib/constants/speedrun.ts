/**
 * 答對後、下一題正式開始前的緩衝秒數（讀秒動畫）。客戶端跟伺服器都要用同一個數字：
 * 伺服器算最終成績時會扣掉這段緩衝時間（這段期間音樂是停止的，不算「真正在播放」，
 * 不該算進計時，見 speedrunSession.ts 的說明），客戶端則用來控制緩衝畫面的倒數動畫要跑多久。
 * 兩邊沒對齊的話，畫面上顯示的碼表跟伺服器最終認定的成績會兜不起來。
 */
export const SPEEDRUN_TRANSITION_SEC = 2;

/**
 * 每一題「等待音樂真的開始播放」最多可以從成績扣除的毫秒數上限（見 speedrunSession.ts
 * reportAudioStarted 的完整說明）。這個數字是刻意設的安全閥：這段等待時間本質上是客戶端
 * 回報的（沒辦法像緩衝畫面那樣用固定公式算，因為每個人的網路狀況不一樣），沒有上限的話
 * 有心人可以刻意慢一點回報「音樂開始了」藉此無限灌水縮短成績；設了上限之後，就算真的
 * 被濫用，每題最多也只能佔到這麼多便宜，10 題累積下來的影響有限。5 秒是抓一般網路狀況下
 * 音訊緩衝合理會發生的等待時間，真的等超過 5 秒沒開始播放，多半代表來源本身有問題，
 * 不是單純網路延遲，這種情況不再繼續當作「合理的緩衝等待」扣除。
 */
export const SPEEDRUN_AUDIO_WAIT_CAP_MS = 5000;

/**
 * 單題計分耗時的下限（毫秒）。伺服器結算每一題時，扣完客戶端回報的等待時間之後，
 * 單題成績不會低於這個值。用意：就算有人偽造等待時間回報、或用腳本秒答，成績也有一個
 * 真人不可能突破的底線（10 題至少 15 秒），無法刷出 0 秒之類的假成績。
 */
export const SPEEDRUN_MIN_QUESTION_MS = 1500;

/**
 * 伺服器強制答錯鎖定時，容許網路抖動的誤差（毫秒）。客戶端鎖定 WRONG_ANSWER_LOCKOUT_MS，
 * 伺服器實際執行的鎖定時間是「鎖定時間 − 這個容許值」，避免正常玩家因為網路延遲被誤擋。
 */
export const SPEEDRUN_LOCKOUT_TOLERANCE_MS = 500;
